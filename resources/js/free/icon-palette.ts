/**
 * The client-side handle onto the app's fixed, curated icon palette — not
 * a free-form icon picker. app/Support/IconKey.php is the single source
 * of truth for which keys exist and their display labels; this module
 * just holds whatever it sent down as the `iconPalette` shared Inertia
 * prop (see HandleInertiaRequests::share()), seeded once at boot by
 * setIconPalette() (see app.ts). The server never accepts or sees an
 * actual icon reference for these slots — only a KEY (SettingsController
 * validates every *_icon_key with Rule::enum(IconKey::class)) — the
 * KEY -> real Lucide component mapping below is the ONE place that
 * translates our own stable names to whatever this app's installed icon
 * set currently calls them. If a future upgrade renames one of these
 * imports, this is the only line that needs to change — every *_icon_key
 * ever stored in the database keeps working unmodified. (The palette used
 * to be Font Awesome; the swap to Lucide changed nothing but this file.)
 *
 * Where Lucide has no equivalent a key is either drawn locally below in
 * Lucide's own stroke style (traffic light, checkered flag) or mapped to
 * the nearest glyph. Stored keys outlive any one icon set, so two keys can
 * share a glyph (e.g. battery-three-quarters and battery-full, since
 * Lucide's batteries have only four levels) rather than disappear.
 */
