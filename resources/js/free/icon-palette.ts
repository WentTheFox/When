let icons: IconOption[] = [];
let defaultKeys: Record<IconSlot, string> = {
  free: '',
  busy: '',
  work: '',
  school: '',
  public: '',
  sleep: '',
  highlighted: '',
};

/** Called once at boot (app.ts) with the `iconPalette` shared prop from the initial page load. */
export function setIconPalette(list: IconOption[], defaults: Record<IconSlot, string>): void {
  icons = list;
  defaultKeys = defaults;
}

export function getIconPalette(): IconOption[] {
  return icons;
}

export function getDefaultIconKey(slot: IconSlot): string {
  return defaultKeys[slot];
}

/** Resolves a (possibly unset/invalid) stored key to an actual icon for the given slot, falling back to that slot's default. */
export function resolveIcon(key: string | null | undefined, slot: IconSlot): PaletteIcon {
  const resolvedKey = (key && ICON_KEY_TO_LUCIDE[key]) ? key : defaultKeys[slot];

  return ICON_KEY_TO_LUCIDE[resolvedKey] ?? Check;
}

export function paletteIconFor(key: string): PaletteIcon | undefined {
  return ICON_KEY_TO_LUCIDE[key];
}
